#!/usr/bin/env python3
"""Bake the first safe native-tile biome overlay into ROM (no ARM generation).
Only exact General grass tiles on reviewed ordinary Hoenn land routes.
Never change movement geometry, events, warps, puzzle maps or map seams.
"""
import argparse
import json
import re
import struct
from pathlib import Path
from genesis_biomes import assign
from genesis_climate import noise
from genesis_puzzles import review_reasons

SEED = 0x47454E33
GRASS, TALL, SAND = 0x001, 0x00D, 0x121
ID, COLLISION = 0x03FF, 0x0C00
MODULE = 4
# Only families with safe, existing native art for this pilot.
SUPPORTED = {"plains", "forest", "savanna", "desert", "badlands", "jungle"}


def load_words(path):
    data = path.read_bytes()
    if len(data) % 2:
        raise ValueError(f"odd word count: {path}")
    return struct.unpack("<"+"H"*(len(data)//2), data)


def protected(meta,x,y,w,h):
    for c in meta.get("connections") or []:
        direction = c["direction"]
        if ((direction == "left" and x < 7) or
            (direction == "right" and x >= w-7) or
            (direction == "up" and y < 7) or
            (direction == "down" and y >= h-7)):
            return True
    for key,radius in (("object_events",2),("warp_events",2),
                       ("coord_events",3),("bg_events",1)):
        for e in meta.get(key) or []:
            rx = radius + int(e.get("movement_range_x",0))
            ry = radius + int(e.get("movement_range_y",0))
            if abs(x-e["x"])<=rx and abs(y-e["y"])<=ry:
                return True
    return False


def make_edits(meta,layout,words,map_id):
    w,h=layout["width"],layout["height"]
    if len(words)!=w*h:
        raise ValueError("layout dimensions differ from native map")
    mw,mh=(w+MODULE-1)//MODULE,(h+MODULE-1)//MODULE
    plan=assign(SEED,map_id,mw,mh,eligible=SUPPORTED)
    edits=[]
    for y in range(h):
        for x in range(w):
            k=y*w+x
            old=words[k]
            tile=old&ID
            if tile not in (GRASS,TALL) or old&COLLISION or protected(meta,x,y,w,h):
                continue
            cell=plan["cells"][(y//MODULE)*mw+x//MODULE]
            blend=cell["blend"]
            dry=sum(blend.get(n,0) for n in ("desert","badlands","savanna"))/255
            open_land=sum(blend.get(n,0) for n in ("plains","savanna","desert","badlands"))/255
            signal=noise(SEED^map_id,x,y,0,12)
            # The sandy tile is a complete native normal-behavior floor.
            # Keep some tall grass for encounters; no new movement mechanics.
            if dry>.15 and signal < dry*(.86 if tile==GRASS else .52):
                target=SAND
            elif tile==TALL and signal < .14+.30*open_land:
                target=GRASS
            else:
                continue
            new=(old&~ID)|target
            if new!=old:
                assert (new&~ID)==(old&~ID)
                edits.append((x,y,old,new))
    return plan["dominant"],edits


def bake(root,output):
    attributes=load_words(root/"data/tilesets/primary/general/metatile_attributes.bin")
    if (attributes[GRASS],attributes[TALL],attributes[SAND])!=(0,2,0):
        raise ValueError("General tileset contract changed")
    layouts={l["id"]:l for l in json.loads((root/"data/layouts/layouts.json").read_text())["layouts"]}
    blocks=[]
    for p in sorted((root/"data/maps").glob("Route*/map.json")):
        if not re.fullmatch(r"Route1[0-3][0-9]",p.parent.name):
            continue
        meta=json.loads(p.read_text())
        l=layouts[meta["layout"]]
        if (meta["map_type"]!="MAP_TYPE_ROUTE" or l.get("layout_version")!="emerald"
                or l["primary_tileset"]!="gTileset_General"
                or review_reasons(p.parent.name,meta)):
            continue
        words=load_words(root/l["blockdata_filepath"])
        biome,edits=make_edits(meta,l,words,int(p.parent.name[5:]))
        if edits:
            blocks.append((meta["id"],l["width"],l["height"],biome,edits))
    if not blocks:
        raise ValueError("no safe native route edits baked")
    lines=["/* Generated by genesis_bake.py; do not edit. */"]
    for mid,w,h,biome,edits in blocks:
        lines.append(f"static const struct GenesisBakedEdit sBaked_{mid}[] = {{ /* {biome} */")
        lines.extend(f"    {{{x}, {y}, 0x{old:04X}, 0x{new:04X}}}," for x,y,old,new in edits)
        lines.append("};")
    lines.append("static const struct GenesisBakedMap sBakedMaps[] = {")
    for mid,w,h,biome,edits in blocks:
        lines.append(f"    {{{mid}, {w}, {h}, ARRAY_COUNT(sBaked_{mid}), sBaked_{mid}}},")
    lines.append("};")
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text("\n".join(lines)+"\n")
    print(f"Genesis bake: {len(blocks)} routes, {sum(len(b[-1]) for b in blocks)} safe edits")
    for mid,w,h,biome,edits in blocks:
        print(f"  {mid}: {biome}, {len(edits)} edits")


if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--root",type=Path,default=Path("."))
    p.add_argument("--output",type=Path,required=True)
    a=p.parse_args()
    bake(a.root,a.output)
