#!/usr/bin/env python3
"""Check Unholy route Gear pickups before generating a ROM."""

import json
import re
import struct
from collections import deque
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LAYOUTS = {
    layout["id"]: layout
    for layout in json.loads((ROOT / "data/layouts/layouts.json").read_text())["layouts"]
}

# Map, Gear item, pickup flag, position, and a known reachable starting point.
PICKUPS = [
    ("Route110", "ITEM_GEAR_LENTE_CERTEZA", "FLAG_UNHOLY_ROUTE110_LENTE_CERTEZA", (34, 65), (30, 69)),
    ("Route111", "ITEM_GEAR_PIEDRA_AFILAR", "FLAG_UNHOLY_ROUTE111_PIEDRA_AFILAR", (16, 58), (12, 54)),
    ("Route115", "ITEM_GEAR_GUANTES_COHETE", "FLAG_UNHOLY_ROUTE115_GUANTES_COHETE", (22, 11), (18, 7)),
    ("Route117", "ITEM_GEAR_BATERIA_RESERVA", "FLAG_UNHOLY_ROUTE117_BATERIA_RESERVA", (9, 17), (16, 18)),
    ("Route119", "ITEM_GEAR_BOTON_PANICO", "FLAG_UNHOLY_ROUTE119_PANIC", (12, 121), None),
    ("Route120", "ITEM_GEAR_CASCO_HOPLITA", "FLAG_UNHOLY_ROUTE120_HOPLITA", (20, 55), None),
    ("Route121", "ITEM_GEAR_BOTAS_UMBRAL", "FLAG_UNHOLY_ROUTE121_BOTAS_UMBRAL", (46, 13), (38, 13)),
    ("Route123", "ITEM_GEAR_TUNICA_RUNICA", "FLAG_UNHOLY_ROUTE123_TUNICA", (57, 16), None),
    ("MtPyre_4F", "ITEM_GEAR_VELO_CRIPTICO", "FLAG_UNHOLY_MT_PYRE_VELO_CRIPTICO", (8, 12), (3, 11)),
    ("ShoalCave_LowTideIceRoom", "ITEM_GEAR_PERMAFROST_FRAGMENT", "FLAG_UNHOLY_SHOAL_CAVE_PERMAFROST", (8, 4), (12, 8)),
    ("Underwater_Route127", "ITEM_GEAR_ARIETE_NAUTILO", "FLAG_UNHOLY_UNDERWATER127_ARIETE_NAUTILO", (59, 12), (57, 5)),
    ("VictoryRoad_B1F", "ITEM_GEAR_NIHIL_ENGINE", "FLAG_UNHOLY_VICTORY_ROAD_NIHIL_ENGINE", (35, 10), (32, 3)),
]

# Regression cases reported in actual play. Keep these independent of the Gear
# reward audit so a vanilla item ball cannot silently become decoration.
REPORTED_PICKUPS = [
    ("Route102", "ITEM_POTION", "FLAG_ITEM_ROUTE_102_POTION", (11, 15), (11, 14)),
]

# From Littleroot through Wattson, verify the ordinary pickups as a group,
# not just the Route 102 screenshot. The two later badge-gated additions use
# their own scripts and are audited by validate_world_updates.py.
EARLY_GAME_NATIVE_MINIMUMS = {
    "Route102": 1, "Route103": 2, "Route104": 4,
    "Route105": 1, "Route106": 1, "Route108": 1,
    "Route109": 2, "Route110": 4, "Route116": 5,
    "PetalburgWoods": 4, "RusturfTunnel": 2, "GraniteCave_1F": 1,
}


def audit_all_item_balls():
    """Catch inert/misconfigured visible Poké Balls on every game map.

    Scripted encounters and gifts legitimately have no item in their template;
    only Common_EventScript_FindItem requires a native item ID and pickup flag.
    The GBA build checks that referenced script labels actually link.
    """
    items_source = (ROOT / "include/constants/items.h").read_text()
    item_names = set(re.findall(r"^\s*(ITEM_\w+)\s*=", items_source, re.MULTILINE))
    # Named TM/HM item constants are generated by the C metaprogramming
    # macros, so they do not appear as literal enum members in items.h.
    tmhm_source = (ROOT / "include/constants/tms_hms.h").read_text()
    tm_source, _, remainder = tmhm_source.partition("#define FOREACH_HM(F)")
    hm_source, _, _ = remainder.partition("#define FOREACH_TMHM(F)")
    item_names.update("ITEM_TM_" + name for name in re.findall(r"\bF\((\w+)\)", tm_source))
    item_names.update("ITEM_HM_" + name for name in re.findall(r"\bF\((\w+)\)", hm_source))
    flags_source = (ROOT / "include/constants/flags.h").read_text()
    flags_source += (ROOT / "include/constants/flags_frlg.h").read_text()
    flag_names = set(re.findall(r"^#define\s+(FLAG_\w+)\b", flags_source, re.MULTILINE))

    errors = []
    total = native = scripted = 0
    used_native_flags = {}
    early_native_counts = {name: 0 for name in EARLY_GAME_NATIVE_MINIMUMS}
    for path in sorted((ROOT / "data/maps").glob("*/map.json")):
        map_data = json.loads(path.read_text())
        layout = LAYOUTS.get(map_data.get("layout"))
        if layout is not None:
            width, height = layout["width"], layout["height"]
            raw_tiles = (ROOT / layout["blockdata_filepath"]).read_bytes()
            map_tiles = struct.unpack(f"<{width * height}H", raw_tiles)
        else:
            width = height = 0
            map_tiles = ()

        def tile_at(x, y):
            if 0 <= x < width and 0 <= y < height:
                return map_tiles[y * width + x]
            return None

        for obj in map_data.get("object_events", []):
            if obj.get("graphics_id") != "OBJ_EVENT_GFX_ITEM_BALL":
                continue

            total += 1
            script = obj.get("script")
            location = f"{path.parent.name} ({obj.get('x')},{obj.get('y')})"
            if script in (None, "", "0", "NULL"):
                errors.append(f"{location}: visible item ball has no interaction script")
                continue

            if script != "Common_EventScript_FindItem":
                scripted += 1
                continue

            native += 1
            if path.parent.name in early_native_counts:
                early_native_counts[path.parent.name] += 1
            item = obj.get("trainer_sight_or_berry_tree_id")
            flag = obj.get("flag")
            if item not in item_names or item == "ITEM_NONE":
                errors.append(f"{location}: missing/undefined native pickup item {item}")
            if flag not in flag_names or flag == "0":
                errors.append(f"{location}: missing/undefined native pickup flag {flag}")
            if flag in used_native_flags:
                errors.append(f"{location}: pickup flag {flag} reused by {used_native_flags[flag]}")
            used_native_flags[flag] = location

            x, y, elevation = obj["x"], obj["y"], obj["elevation"]
            tile = tile_at(x, y)
            if tile is None:
                errors.append(f"{location}: item ball is outside its map's walkable layout")
                continue
            tile_elevation = (tile >> 12) & 0xF
            if (tile >> 10) & 3:
                errors.append(f"{location}: item ball sits on an impassable tile")
            if elevation and tile_elevation and elevation != tile_elevation:
                errors.append(f"{location}: object elevation {elevation} mismatches tile elevation {tile_elevation}")

            neighbors = (tile_at(x + dx, y + dy) for dx, dy in ((0, 1), (0, -1), (1, 0), (-1, 0)))
            if not any(neighbor is not None
                       and (neighbor >> 10) & 3 == 0
                       and (elevation == 0 or (neighbor >> 12) & 0xF in (0, elevation))
                       for neighbor in neighbors):
                errors.append(f"{location}: no adjacent passable tile at matching elevation for pressing A")

    if total == 0:
        errors.append("no visible item-ball events found; check map search path")
    for map_name, minimum in EARLY_GAME_NATIVE_MINIMUMS.items():
        if early_native_counts[map_name] < minimum:
            errors.append(f"{map_name}: only {early_native_counts[map_name]} native balls (expected at least {minimum})")
    return errors, (total, native, scripted)


def validate_pickup(entry, items, flags):
    map_name, item, flag, position, start = entry
    errors = []
    map_data = json.loads((ROOT / f"data/maps/{map_name}/map.json").read_text())
    layout = LAYOUTS[map_data["layout"]]
    width, height = layout["width"], layout["height"]
    data = (ROOT / layout["blockdata_filepath"]).read_bytes()
    tiles = struct.unpack(f"<{width * height}H", data)

    def walkable(pos, elevation):
        x, y = pos
        if not (0 <= x < width and 0 <= y < height):
            return False
        tile = tiles[y * width + x]
        return (tile >> 10) & 3 == 0 and tile >> 12 == elevation

    def adjacent(pos):
        x, y = pos
        return [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]

    objects = map_data.get("object_events", [])
    found = [obj for obj in objects if obj.get("flag") == flag]
    if len(found) != 1:
        return [f"{map_name}: {flag} occurs {len(found)} times, expected once"]

    obj = found[0]
    if obj["graphics_id"] != "OBJ_EVENT_GFX_ITEM_BALL":
        errors.append("wrong overworld graphic")
    if obj["script"] != "Common_EventScript_FindItem":
        errors.append("missing pickup interaction script")
    if obj["trainer_sight_or_berry_tree_id"] != item or item not in items:
        errors.append("missing or mismatched Gear item")
    if flag not in flags:
        errors.append("pickup flag is undefined")
    if (obj["x"], obj["y"]) != position:
        errors.append("unexpected pickup coordinates")
    if len(objects) > 64:
        errors.append("map exceeds saved event-template capacity")
    elevation = obj["elevation"]
    if not walkable(position, elevation):
        errors.append("pickup tile is impassable or at wrong elevation")
    if not any(walkable(neighbor, elevation) for neighbor in adjacent(position)):
        errors.append("no adjacent walkable tile from which to press A")

    occupied = (
        [(other["x"], other["y"]) for other in objects if other is not obj]
        + [(event["x"], event["y"]) for key in ("warp_events", "coord_events", "bg_events")
           for event in map_data.get(key, [])]
    )
    if position in occupied:
        errors.append("pickup overlaps another event")

    if start is not None:
        # Underwater warp coordinates can have a different elevation. Starting
        # from their adjacent seabed tiles still checks the actual path.
        reachable = [start] if walkable(start, elevation) else [
            neighbor for neighbor in adjacent(start) if walkable(neighbor, elevation)
        ]
        queue = deque(reachable)
        seen = set(reachable)
        while queue and position not in seen:
            for neighbor in adjacent(queue.popleft()):
                if neighbor not in seen and walkable(neighbor, elevation):
                    seen.add(neighbor)
                    queue.append(neighbor)
        if position not in seen:
            errors.append("pickup is disconnected from its access area")

    return [f"{map_name} {position}: {error}" for error in errors]


def main():
    items = (ROOT / "include/constants/items.h").read_text()
    flags = (ROOT / "include/constants/flags.h").read_text()
    errors = []
    seen = set()
    for entry in PICKUPS + REPORTED_PICKUPS:
        if entry[2] in seen:
            errors.append(f"duplicate pickup flag: {entry[2]}")
        seen.add(entry[2])
        errors.extend(validate_pickup(entry, items, flags))

    all_ball_errors, counts = audit_all_item_balls()
    errors.extend(all_ball_errors)

    # Regression: ordinary item balls must be resolved before the effect
    # preflight, which used to silently discard their A-button interaction.
    interaction = (ROOT / "src/field_control_avatar.c").read_text()
    start = interaction.index("static bool8 TryStartInteractionScript(struct MapPosition *position")
    end = interaction.index("static const u8 *GetVisibleItemBallScript(struct MapPosition *position", start)
    flow = interaction[start:end]
    if flow.find("GetVisibleItemBallScript(position, direction)") < 0 or (
        flow.find("GetVisibleItemBallScript(position, direction)") > flow.find("GetInteractionScript(position, metatileBehavior")
    ):
        errors.append("visible Poké Balls no longer bypass the generic interaction-effect preflight")

    if errors:
        for error in errors:
            print(f"ERROR: {error}")
        raise SystemExit(1)
    print(f"OK: {len(PICKUPS)} unique Gear pickups have valid scripts, rewards, tiles, and flags")
    print(f"OK: {len(REPORTED_PICKUPS)} reported inert pickup locations have valid map templates")
    print(f"OK: {counts[0]} visible item balls audited ({counts[1]} native pickups, {counts[2]} scripted encounters/gifts)")
    print(f"OK: {sum(EARLY_GAME_NATIVE_MINIMUMS.values())} early-game native pickups covered through badge three")


if __name__ == "__main__":
    main()
